namespace Utu.Cli;

/// <summary>The help text of utu.</summary>
public static class HelpText
{
    /// <summary>One line description of utu.</summary>
    public const string Summary = "Upload videos to YouTube from a folder of .mp4 files.";

    /// <summary>The complete help text.</summary>
    public static string[] Lines =>
    [
        "Usage:",
        "  utu <command> [--option=<value>]",
        "",
        "Commands:",
        "  help      Show this help. This is also the default when no command is given.",
        "  init      Discover the .mp4 files of the folder and create utu.json with placeholders.",
        "            The file names every available setting in 'defaults' and leaves it",
        "            null, so that nothing is overridden; the videos only get file, title",
        "            and thumbnail. A 'publishSchedule' spreads the publication times",
        "            over the videos. Also creates the global utu.json of the user when",
        "            it is missing.",
        "  schedule  Recompute the publication times of the videos from the",
        "            'publishSchedule' of the configuration: every video gets a new",
        "            time, in the order of the file.",
        "  upload    Upload the .mp4 files according to utu.json.",
        "",
        "Options:",
        "  --config=<file>          Configuration file (default: utu.json). A file named",
        "                           explicitly is used as is, without the global layer.",
        "  --folder=<folder>        Folder that paths are resolved against (default: .).",
        "  --force                  Upload again, even when the upload already completed.",
        "  --dry-run                Show the plan without uploading or writing.",
        "  --only=<pattern>         Only the matching videos; repeat or separate with ','.",
        "  --jobs=<n>               Parallel uploads (default: channel.parallelUploads).",
        "  --retries=<n>            Attempts per operation (default: 3).",
        "  --no-resume              Restart interrupted uploads instead of continuing them.",
        "  --recursive               init: also search sub folders.",
        "  --category=<name>        init: category of the videos (built in: Music).",
        "  --client-secrets=<file>  OAuth client secrets of a desktop client.",
        "  --verbose                Print every detail.",
        "  --no-color               Plain output without colours.",
        "  --help                   Show this help.",
        "",
        "Configuration:",
        "  Settings are layered. The first layer that defines a value wins:",
        "    1. the entry of the video in the folder utu.json,",
        "    2. the 'defaults' of the folder utu.json,",
        "    3. the 'defaults' and 'channel' of the global utu.json in the home folder,",
        "    4. the built in values of utu.",
        "",
        "  The global configuration lives in <.utu>/utu.json (Windows:",
        "  %USERPROFILE%\\.utu\\utu.json). Set UTU_HOME to use another folder. It holds",
        "  channel parameters and the defaults that every folder shares:",
        "",
        "    {",
        "      \"channel\": { \"name\": \"My channel\", \"clientSecretsFile\": \"client_secrets.json\" },",
        "      \"defaults\": { \"category\": \"Music\", \"privacy\": \"private\" }",
        "    }",
        "",
        "  A folder only needs what differs from the global configuration:",
        "",
        "    {",
        "      \"defaults\": { \"tags\": [\"music\"] },",
        "      \"videos\": [",
        "        { \"file\": \"video.mp4\", \"title\": \"Video\", \"thumbnail\": \"video.jpg\" }",
        "      ]",
        "    }",
        "",
        "  Merging is per setting, lists and dictionaries are replaced as a whole.",
        "  Relative paths are resolved against the folder of the file that defines",
        "  them, so a path named by the global utu.json belongs in <.utu>.",
        "  A blank value means 'not set' and is inherited.",
        "",
        "  'publishSchedule' is a crontab expression and only belongs in 'defaults',",
        "  never in a video entry. 'utu init' hands the first time it matches after",
        "  the run to the first video in file order, the next time to the second, and",
        "  so on, leaving the videos that already have a 'publishAt' alone. Without",
        "  it nothing is scheduled. 'utu schedule' uses the expression differently:",
        "  it recomputes the 'publishAt' of every video and writes it back, which is",
        "  how the times follow a configuration that changed after 'utu init'.",
        "",
        "    \"defaults\": { \"publishSchedule\": \"0 9 * * *\", \"privacy\": \"private\" }",
        "",
        "  The fields are minute, hour, day of month, month and day of week; an",
        "  optional leading field adds seconds. A field accepts '*', a list ('1,15'),",
        "  a range ('8-17'), a step ('*/15') and month or weekday names ('JAN',",
        "  'MON-FRI'); '@hourly', '@daily', '@weekly', '@monthly' and '@yearly' name",
        "  the common cases. Times are read in the local time zone. YouTube accepts a",
        "  publication time only on a private video, so 'privacy' has to be 'private'.",
        "",
        "  'utu init' writes the global utu.json once, when it does not exist yet, with",
        "  every setting and the value utu would use anyway, so the file doubles as",
        "  documentation. An existing file is never overwritten.",
        "",
        "  The utu.json of a folder gets a 'defaults' block that names every setting",
        "  with a null placeholder; its video entries only carry file, title and",
        "  thumbnail.",
        "",
        "Authentication:",
        "  The first upload opens a browser. The token is cached in <.utu>/auth",
        "  (%USERPROFILE%\\.utu\\auth by default), so later runs do not ask again. The",
        "  cached token is protected with the Windows data protection API and is never",
        "  written in clear text; only the Windows user that authorized can read it.",
        "  The client secrets live in the same folder: client_secrets.json is protected",
        "  on first use into client_secrets.json.protected, the plain file is deleted",
        "  and only the protected file is read afterwards.",
    ];
}
